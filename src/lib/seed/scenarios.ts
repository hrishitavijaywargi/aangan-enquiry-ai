export const scenarioByKey = (k: string) => SCENARIOS.find((s) => s.key === k);

/** The simulated caller's reply to whatever the agent just asked. */
export function scenarioReply(sc: Scenario, question: QuestionKey | undefined, callerTurn: number): string | undefined {
  if (callerTurn === 0) return sc.opening;
  if (question && sc.answers[question]) return sc.answers[question];
  if (question === "anything_else") return BYE;
  if (question === "need") return sc.answers.need ?? "I'd like to discuss a project.";
  return "I'm not sure, sorry.";
}

/** "2026-09-02 10:23" IST → Date (UTC). */
export function istToDate(ist: string): Date {
  return new Date(ist.replace(" ", "T") + ":00+05:30");
}
